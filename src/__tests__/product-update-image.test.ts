import { describe, it, expect, vi } from 'vitest'

// The mobile admin routes are protected by Firebase token verification
// (mobileAdminAuth). For this persistence test we bypass auth with a passthrough
// so the request reaches ProductRepository.update() directly.
vi.mock('../services/auth.service', () => ({
  mobileAdminAuth: async (_c: any, next: any) => next(),
}))

import { mobileAdminRouter } from '../routes/api-mobile/admin.routes'

describe('PUT /admin/products/:id — image_url persistence (BUG 3)', () => {
  it('persists image_url from the request body into both image columns', async () => {
    const calls: { query: string; params: any[] }[] = []

    // Minimal D1 mock recording every prepared statement so we can assert the
    // UPDATE generated by ProductRepository.update(). Handles both call shapes
    // used on this path: `prepare(sql).run()` (logAdminAudit DDL) and
    // `prepare(sql).bind(...).run()` (the UPDATE + the audit INSERT).
    const mockDb: any = {
      prepare: (query: string) => ({
        bind: (...params: any[]) => ({
          run: async () => {
            calls.push({ query, params })
            return { meta: { changes: 1 } }
          },
          all: async () => ({ results: [] }),
          first: async () => null,
        }),
        run: async () => {
          calls.push({ query, params: [] })
          return { meta: { changes: 1 } }
        },
        all: async () => ({ results: [] }),
        first: async () => null,
      }),
    }

    const imageUrl =
      'https://maasga-website.pages.dev/media/mobile-uploads/test-image.png'

    const res = await mobileAdminRouter.request(
      '/admin/products/1',
      {
        method: 'PUT',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ image_url: imageUrl }),
      },
      { DB: mockDb } as any,
    )

    // update() reports a change → route answers 200 { success: true }.
    expect(res.status).toBe(200)
    expect(await res.json()).toEqual({ success: true })

    // Locate the UPDATE products statement issued by ProductRepository.update().
    const updateCall = calls.find(
      (c) => c.query.startsWith('UPDATE products') && c.query.includes('image_url'),
    )
    expect(updateCall).toBeDefined()
    // Both the normalized column (image_url) and the legacy alias (imageUrl)
    // are written, so the image survives whichever alias the client sends.
    expect(updateCall!.query).toContain('image_url = ?')
    expect(updateCall!.query).toContain('imageUrl = ?')
    // The image URL is bound to both columns (first two params).
    expect(updateCall!.params[0]).toBe(imageUrl)
    expect(updateCall!.params[1]).toBe(imageUrl)
    // The product id from the route path is bound last.
    expect(updateCall!.params[updateCall!.params.length - 1]).toBe(1)
  })
})
